//! `compare` (current result vs baseline) and the generated `bench/HISTORY.md`.

use std::path::Path;

use anyhow::{Context, Result};

use crate::env::table;
use crate::guard::{METRICS, Status};
use crate::record::{BASELINE, Record, load_all};

pub const HISTORY: &str = "bench/HISTORY.md";

/// Metrics shown as columns of the history table; the trends cover all of them.
const HISTORY_COLUMNS: &[&str] = &[
    "b1_p50_ms",
    "b1_p99_ms",
    "b2_changes_per_s",
    "b2_drain_s",
    "b2_store_commit_ms",
    "b3_full_ms",
    "b3_delta_ms",
    "b3_delta_bytes",
    "b3_none_ms",
];

/// Prints the comparison, rewrites HISTORY.md, and returns whether anything regressed.
pub fn compare(current_path: &Path) -> Result<bool> {
    let current = Record::load(current_path)?;
    let baseline = Path::new(BASELINE)
        .exists()
        .then(|| Record::load(Path::new(BASELINE)))
        .transpose()?;
    let rows = comparison(baseline.as_ref(), &current);
    write_history(baseline.as_ref(), &current, &rows)?;
    eprintln!("wrote {HISTORY}");

    let Some(base) = &baseline else {
        println!(
            "No baseline ({BASELINE}). To create one from this run:\n  walrus-bench accept {}",
            current_path.display()
        );
        return Ok(false);
    };
    println!(
        "{} (current) vs {} (baseline)\n",
        current.label(),
        base.label()
    );
    println!("{}", render_table(&rows));
    if base.hardware != current.hardware {
        println!(
            "WARNING: different hardware, numbers are not comparable.\n  baseline: {}\n  current:  {}\n",
            base.hardware, current.hardware
        );
    }
    let regressed: Vec<&str> = rows
        .iter()
        .filter(|r| r.status == Some(Status::Regression))
        .map(|r| r.key)
        .collect();
    if regressed.is_empty() {
        println!("No regressions.");
    } else {
        println!("REGRESSIONS: {}", regressed.join(", "));
    }
    Ok(!regressed.is_empty())
}

pub fn accept(path: &Path) -> Result<()> {
    Record::load(path)?; // refuse anything that is not a result
    std::fs::copy(path, BASELINE)
        .with_context(|| format!("copying {} to {BASELINE}", path.display()))?;
    eprintln!("baseline is now {} ({BASELINE})", path.display());
    Ok(())
}

struct Row {
    key: &'static str,
    base: Option<String>,
    current: Option<String>,
    delta: String,
    /// `None` when there is nothing to compare (not measured in one of the runs).
    status: Option<Status>,
    label: String,
}

fn comparison(baseline: Option<&Record>, current: &Record) -> Vec<Row> {
    METRICS
        .iter()
        .filter(|m| current.metrics.contains_key(m.key))
        .map(|m| {
            let value = current.metrics[m.key];
            let base = baseline.and_then(|b| b.metrics.get(m.key)).copied();
            Row {
                key: m.key,
                label: format!("{} ({})", m.key, m.unit),
                base: base.map(|b| m.format(b)),
                current: Some(m.format(value)),
                delta: match base {
                    Some(b) if b != 0.0 => format!("{:+.1}%", (value - b) / b * 100.0),
                    Some(b) if value == b => "0.0%".into(),
                    Some(_) => "n/a".into(),
                    None => String::new(),
                },
                status: base.map(|b| m.judge(b, value)),
            }
        })
        .collect()
}

fn render_table(rows: &[Row]) -> String {
    let cells: Vec<Vec<String>> = rows
        .iter()
        .map(|r| {
            vec![
                r.label.clone(),
                r.base.clone().unwrap_or_else(|| "-".into()),
                r.current.clone().unwrap_or_else(|| "-".into()),
                r.delta.clone(),
                r.status.map_or("not in baseline", Status::text).into(),
            ]
        })
        .collect();
    table(&["metric", "baseline", "current", "Δ%", "status"], &cells)
}

fn write_history(baseline: Option<&Record>, current: &Record, rows: &[Row]) -> Result<()> {
    let runs = load_all()?;
    let mut out = String::from(
        "# Benchmark history\n\n\
         Generated by `walrus-bench compare` (run by `scripts/bench.sh`); do not edit. Every run \
         writes `bench/results/<date>-<commit>.json` next to its report, and this page is built \
         from all of them. `bench/baseline.json` is the accepted reference: `compare` fails on a \
         regression against it, and `scripts/bench.sh --accept` replaces it after an intentional \
         change. Numbers are only comparable between runs on the same machine.\n\n",
    );
    match baseline {
        Some(b) => out.push_str(&format!(
            "Baseline: {} on {} (Postgres {}, {} build).\n\n",
            b.label(),
            b.hardware,
            b.postgres,
            b.profile
        )),
        None => out.push_str("Baseline: none yet (`scripts/bench.sh --accept` creates it).\n\n"),
    }

    out.push_str(&format!(
        "## Latest vs baseline\n\nRun: {}.\n\n",
        current.label()
    ));
    out.push_str(&if baseline.is_some() {
        render_table(rows)
    } else {
        "No baseline to compare against.\n".into()
    });

    out.push_str("\n## History\n\nNewest first; blank where a run did not measure the metric.\n\n");
    let mut headers = vec!["date", "commit"];
    headers.extend(HISTORY_COLUMNS);
    let mut body = Vec::new();
    for (_, r) in runs.iter().rev() {
        let mut row = vec![
            r.date.clone(),
            format!("`{}`{}", r.commit, if r.dirty { " dirty" } else { "" }),
        ];
        for key in HISTORY_COLUMNS {
            row.push(cell(r, key));
        }
        body.push(row);
    }
    out.push_str(&table(&headers, &body));

    out.push_str("\n## Trends\n\nOldest to newest run, left to right.\n\n");
    let mut trend_rows = Vec::new();
    for m in METRICS {
        let series: Vec<f64> = runs
            .iter()
            .filter_map(|(_, r)| r.metrics.get(m.key).copied())
            .collect();
        let (Some(&latest), Some(min), Some(max)) = (
            series.last(),
            series.iter().copied().reduce(f64::min),
            series.iter().copied().reduce(f64::max),
        ) else {
            continue;
        };
        trend_rows.push(vec![
            format!("{} ({})", m.key, m.unit),
            m.label.to_string(),
            sparkline(&series),
            m.format(min),
            m.format(latest),
            m.format(max),
        ]);
    }
    out.push_str(&table(
        &["metric", "what", "trend", "min", "latest", "max"],
        &trend_rows,
    ));
    std::fs::write(HISTORY, out).with_context(|| format!("writing {HISTORY}"))
}

fn cell(r: &Record, key: &str) -> String {
    let m = crate::guard::tracked(key);
    match (r.metrics.get(key), m) {
        (Some(&v), Some(m)) => m.format(v),
        _ => String::new(),
    }
}

fn sparkline(values: &[f64]) -> String {
    const BARS: [char; 8] = ['▁', '▂', '▃', '▄', '▅', '▆', '▇', '█'];
    let min = values.iter().copied().fold(f64::INFINITY, f64::min);
    let max = values.iter().copied().fold(f64::NEG_INFINITY, f64::max);
    values
        .iter()
        .map(|&v| {
            if max == min {
                BARS[3]
            } else {
                BARS[(((v - min) / (max - min)) * 7.0).round() as usize]
            }
        })
        .collect()
}
